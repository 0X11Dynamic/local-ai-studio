#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from `cargo metadata` and frontend/package-lock.json.
// Usage (repo root): node scripts/third-party-notices.mjs
// Rust: packages reachable from the workspace members through normal/build dependencies
// (dev-only dependencies are excluded). npm: production dependencies only (no "dev": true).
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "THIRD_PARTY_NOTICES.md");

// ---- Rust crates ----
const meta = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"],
  { cwd: root, encoding: "utf8", maxBuffer: 1 << 28 }));
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const members = new Set(meta.workspace_members);
const seen = new Set();
const stack = [...members];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    if (d.dep_kinds.some((k) => k.kind === null || k.kind === "build")) stack.push(d.pkg);
  }
}
const crates = [...seen].filter((id) => !members.has(id)).map((id) => byId.get(id));
const crateLicense = (p) => p.license?.replace(/\s+/g, " ").trim() || (p.license_file ? `see ${p.license_file}` : "UNSPECIFIED");
const groupBy = (items, key) => {
  const m = new Map();
  for (const it of items) { const k = key(it); (m.get(k) ?? m.set(k, []).get(k)).push(it); }
  return [...m.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
};

// ---- npm packages (production) ----
const lock = JSON.parse(fs.readFileSync(path.join(root, "frontend", "package-lock.json"), "utf8"));
const npm = [];
for (const [k, v] of Object.entries(lock.packages ?? {})) {
  if (!k || v.dev || v.devOptional) continue; // "" is the root project
  const name = v.name ?? k.split("node_modules/").pop();
  let lic = v.license;
  if (!lic) {
    try { lic = JSON.parse(fs.readFileSync(path.join(root, "frontend", k, "package.json"), "utf8")).license; } catch { /* not installed */ }
  }
  npm.push({ name, version: v.version, license: typeof lic === "object" ? lic?.type : (lic || "UNSPECIFIED") });
}

const section = (title, items, fmt) => {
  let s = `### ${title}\n\n`;
  for (const [lic, list] of groupBy(items, (x) => x.license)) {
    s += `**${lic}** (${list.length})\n\n`;
    s += list.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)).map(fmt).join(", ") + "\n\n";
  }
  return s;
};

const rust = crates.map((p) => ({ name: p.name, version: p.version, license: crateLicense(p) }));
const fmt = (x) => `${x.name} ${x.version}`;

const md = `# Third-party notices

Local AI Studio itself is licensed under the PolyForm Noncommercial License 1.0.0 (see [LICENSE](LICENSE)).
It uses the third-party components below, which keep their own licenses.
This file is generated by \`node scripts/third-party-notices.mjs\`; do not edit the lists by hand.

## Components not in this repository

- **llama.cpp / ggml** (https://github.com/ggml-org/llama.cpp): MIT License, Copyright (c) ggml-org contributors.
  The app downloads the official llama.cpp release binaries (llama-server, ggml-rpc-server and their libraries) at runtime
  on the user's PC; they are not stored in this repository. The license text ships inside each downloaded release.
- **Microsoft Visual C++ runtime DLLs** (\`vcruntime140.dll\`, \`vcruntime140_1.dll\`, \`msvcp140.dll\`):
  redistributed unmodified in the installer under the Microsoft Visual C++ Redistributable license terms
  (https://visualstudio.microsoft.com/license-terms/vs2022-ga-vc-redist/). They are copied from the build machine at
  build time and are not stored in git. The app copies them next to a downloaded llama.cpp runtime so it can start on a clean Windows.
- **Models** downloaded by the user (for example from Hugging Face) are not part of this software and carry their own licenses.

## Rust crates (${rust.length})

Dependencies of the app's Rust workspace (normal and build dependencies, excluding dev-only crates), from \`cargo metadata\`.
Where a crate is dual-licensed (\`A OR B\`), you may choose either license.

${section("By license", rust, fmt).replace(/^### By license\n\n/, "")}
## npm packages (${npm.length}, production only)

Frontend dependencies bundled into the app UI, from \`frontend/package-lock.json\` (development tooling excluded).

${section("By license", npm, fmt).replace(/^### By license\n\n/, "")}`;

fs.writeFileSync(OUT, md.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n");
console.log(`wrote ${path.relative(root, OUT)}: ${rust.length} crates, ${npm.length} npm packages`);
