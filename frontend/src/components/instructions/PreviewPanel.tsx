// Read-only preview of the effective system message, and the one-shot test.
import type { InstructionPreview } from "../../lib/api2";

export type PreviewMode = "chat" | "agent" | "plan";

const MODES: { id: PreviewMode; label: string }[] = [
  { id: "chat", label: "Chat" },
  { id: "agent", label: "Agent" },
  { id: "plan", label: "Plan" },
];

export function tokenSummary(p: InstructionPreview | null): string {
  if (!p) return "Counting…";
  if (p.tokens == null) return `${p.chars.toLocaleString()} characters (load a model to count tokens)`;
  return `${p.tokens.toLocaleString()} tokens${p.n_ctx ? ` of ${p.n_ctx.toLocaleString()} context` : ""}`;
}

export function PreviewPanel({ preview, mode, onMode }: { preview: InstructionPreview | null; mode: PreviewMode; onMode: (m: PreviewMode) => void }) {
  return (
    <section className="panel instr-preview" aria-labelledby="instr-preview-h">
      <div className="instr-panel-head">
        <h3 id="instr-preview-h" className="instr-sub-h">What the model receives</h3>
        <span className="spacer" />
        <div className="instr-seg" role="group" aria-label="Preview for mode">
          {MODES.map((m) => (
            <button key={m.id} type="button" aria-pressed={mode === m.id} onClick={() => onMode(m.id)}>{m.label}</button>
          ))}
        </div>
      </div>
      <p className="instr-note" style={{ margin: 0 }}>
        Read-only. Includes unsaved edits. {mode === "chat" ? "Chat mode never lists tools." : "Tools come from a new chat's defaults (This PC and connected MCP servers)."}
      </p>
      {preview?.parts.map((p) => (
        <div key={p.label}>
          <div className="instr-part-label">{p.label}{p.editable ? "" : " (generated by the app, not editable)"}</div>
          <pre className="preview-text">{p.text}</pre>
        </div>
      ))}
      {preview && preview.parts.length === 0 && <div className="faint">Empty: the model gets no system message.</div>}
      <div className="mono faint instr-tokens" aria-live="polite">
        {tokenSummary(preview)}
        {preview?.templated_tokens != null && `, ${preview.templated_tokens.toLocaleString()} with chat-template markers`}
      </div>
    </section>
  );
}

export function TestPanel({
  prompt, onPrompt, out, testing, onRun,
}: { prompt: string; onPrompt: (v: string) => void; out: string | null; testing: boolean; onRun: () => void }) {
  return (
    <section className="panel instr-test" id="instr-test" aria-labelledby="instr-test-h">
      <h3 id="instr-test-h" className="instr-sub-h">Test</h3>
      <div className="row" style={{ flexWrap: "nowrap" }}>
        <input className="input" style={{ flex: 1 }} aria-label="Test prompt" placeholder="Introduce yourself in two sentences."
          value={prompt} onChange={(e) => onPrompt(e.target.value)}
          onKeyDown={(e) => { if (e.key === "Enter" && !testing) { e.preventDefault(); onRun(); } }} />
        <button type="button" className="btn sm" onClick={onRun} disabled={testing}>{testing ? "Running…" : "Run test"}</button>
      </div>
      <span className="instr-note">One reply from the loaded model in Chat mode, using the text above (saved or not). Nothing is stored.</span>
      {out && <pre className="preview-text" aria-live="polite">{out}</pre>}
    </section>
  );
}
